// Writes TOOLS.md, the tool reference, from the descriptions and input schemas the server itself reports,
// so the reference cannot drift from the code (test/tools-doc.test.ts fails when TOOLS.md is stale).
// Usage: npm run docs:tools
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { createServer } from "../src/server.js";

type Schema = {
	type?: string | string[];
	description?: string;
	enum?: unknown[];
	const?: unknown;
	items?: Schema | Schema[];
	properties?: Record<string, Schema>;
	required?: string[];
	oneOf?: Schema[];
	anyOf?: Schema[];
	minimum?: number;
	maximum?: number;
	exclusiveMinimum?: number;
	minItems?: number;
	maxItems?: number;
	additionalProperties?: Schema | boolean;
};

export const TOOLS_FILE = resolve(fileURLToPath(import.meta.url), "..", "..", "TOOLS.md");

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

const isObject = (s: Schema) => !!s.properties;
const variants = (s: Schema) => s.oneOf ?? s.anyOf;

function typeOf(s: Schema): string {
	if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
	if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(" | ");
	const alts = variants(s);
	if (alts) return [...new Set(alts.map(typeOf))].join(" | ");
	if (Array.isArray(s.items)) return `[${s.items.map(typeOf).join(", ")}]`;
	if (s.items) return `${typeOf(s.items)}[]`;
	if (s.type === "array") return "array";
	if (isObject(s)) return "object";
	if (s.type === "object" && typeof s.additionalProperties === "object") return `map of ${typeOf(s.additionalProperties)}`;
	if (Array.isArray(s.type)) return s.type.join(" | ");
	return s.type ?? "any";
}

function range(s: Schema): string {
	const shown = (n?: number) => n !== undefined && Math.abs(n) < Number.MAX_SAFE_INTEGER;
	const parts: string[] = [];
	if (shown(s.minimum)) parts.push(`≥ ${s.minimum}`);
	if (shown(s.exclusiveMinimum)) parts.push(`> ${s.exclusiveMinimum}`);
	if (shown(s.maximum)) parts.push(`≤ ${s.maximum}`);
	return parts.length ? ` (${parts.join(", ")})` : "";
}

/** The constant that tells an object variant apart (kind, type, …), as `kind = "chain"`. */
function tag(s: Schema): string | undefined {
	for (const [k, p] of Object.entries(s.properties ?? {})) if (p.const !== undefined) return `${k} = ${JSON.stringify(p.const)}`;
}

/** Table rows for an object's properties, then for the fields of nested objects, arrays and variants. */
function rows(schema: Schema, prefix = "", when = "", depth = 0): string[] {
	const required = new Set(schema.required ?? []);
	const out: string[] = [];
	for (const [name, p] of Object.entries(schema.properties ?? {})) {
		const key = `${prefix}${name}`;
		const desc = `${when}${required.has(name) ? "**Required.** " : ""}${p.description ?? ""}${range(p)}`;
		out.push(`| \`${key}\` | ${cell(typeOf(p))} | ${cell(desc.replace(/ {2,}/g, " ").trim())} |`);
		if (depth >= 3) continue;
		const item = Array.isArray(p.items) ? undefined : p.items;
		const inner = isObject(p) ? p : item && (isObject(item) || variants(item)) ? item : undefined;
		const innerPrefix = `${key}${inner === item ? "[]" : ""}.`;
		if (inner && isObject(inner)) out.push(...rows(inner, innerPrefix, "", depth + 1));
		const alts = variants(inner ?? p)?.filter(isObject);
		if (alts?.length)
			for (const v of alts) out.push(...rows(v, inner ? innerPrefix : `${key}.`, tag(v) ? `*When ${tag(v)}.* ` : "", depth + 1));
	}
	return out;
}

export async function toolsMarkdown(): Promise<string> {
	process.env.RYDSPINE_WORKSPACES ??= mkdtempSync(join(tmpdir(), "rydspine-doc-"));
	const [a, b] = InMemoryTransport.createLinkedPair();
	await createServer().connect(a);
	const client = new Client({ name: "tools-doc", version: "0" });
	await client.connect(b);
	const { tools } = await client.listTools();
	await client.close();

	const out = [
		"# Tool reference",
		"",
		"<!-- Generated by `npm run docs:tools` from the server's own tool definitions; do not edit by hand. -->",
		"",
		`rydspine provides ${tools.length} MCP tools. Coordinates are world space unless a tool says otherwise: y points up, units are pixels, rotations are degrees counter-clockwise. Animation values are offsets from the setup pose (\`scalex\`/\`scaley\` are multipliers). See the workflow in [README.md](README.md#workflow).`,
		"",
		tools.map((t) => `[\`${t.name}\`](#${t.name})`).join(" · "),
		"",
	];
	for (const t of tools) {
		out.push(`## ${t.name}`, "", (t.description ?? "").trim(), "");
		const schema = t.inputSchema as Schema;
		const props = Object.entries(schema.properties ?? {});
		if (!props.length) {
			out.push("No parameters.", "");
			continue;
		}
		out.push("| Parameter | Type | Description |", "|---|---|---|", ...rows(schema), "");
	}
	return out.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	writeFileSync(TOOLS_FILE, await toolsMarkdown());
	console.log(`wrote ${TOOLS_FILE}`);
	process.exit(0);
}
